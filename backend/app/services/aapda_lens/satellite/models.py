"""
Data Models and Enums for Satellite Evidence Intelligence in AAPDA Lens.
Defines schemas for satellite observations, proactive monitoring alerts, and correlation outputs.
"""

from datetime import datetime, timezone
from enum import Enum
from typing import Dict, Any, List, Optional
from pydantic import BaseModel, Field, ConfigDict


class DataProvenance(str, Enum):
    REAL = "REAL"
    SIMULATED = "SIMULATED"


class SatellitePlatform(str, Enum):
    SENTINEL_1 = "Copernicus Sentinel-1 SAR"
    SENTINEL_2 = "Copernicus Sentinel-2 MSI"
    NASA_FIRMS = "NASA FIRMS (VIIRS/MODIS)"
    COPERNICUS_EMS = "Copernicus Emergency Management Service"
    LANDSAT_8 = "USGS/NASA Landsat 8-9 OLI"
    SIMULATED_PLATFORM = "Simulated Constellation Sensor"


class SensorType(str, Enum):
    SAR_C_BAND = "C-Band Synthetic Aperture Radar"
    OPTICAL_MULTISPECTRAL = "Multispectral Optical"
    THERMAL_INFRARED = "Thermal Infrared"
    RADAR_ALTIMETRY = "Radar Altimetry"


class ObservationStatus(str, Enum):
    SUPPORTING_OBSERVATION_AVAILABLE = "supporting_observation_available"
    CONFLICTING_OBSERVATION_DETECTED = "conflicting_observation_detected"
    NO_RELEVANT_OBSERVATION_AVAILABLE = "no_relevant_observation_available"
    SATELLITE_ANALYSIS_PENDING = "satellite_analysis_pending"
    INSUFFICIENT_COVERAGE_OR_QUALITY = "insufficient_coverage_or_quality"


class SatelliteObservation(BaseModel):
    """
    Standardized record of a single satellite overpass observation.
    Must maintain provenance, coverage, resolution, and sensor physics.
    """
    evidence_id: str
    provider: str
    platform: SatellitePlatform
    sensor: SensorType
    product_identifier: str
    acquisition_time: datetime
    processing_time: datetime
    min_lat: float
    max_lat: float
    min_lng: float
    max_lng: float
    center_lat: float
    center_lng: float
    coverage_radius_km: float = 30.0
    resolution: str = "10m"
    cloud_coverage: Optional[float] = Field(None, ge=0.0, le=1.0)
    observation_type: str  # e.g., "sar_interferometry", "optical_surface_change", "thermal_anomaly"
    anomaly_detected: bool = False
    anomaly_description: Optional[str] = None
    source_reference: str
    data_provenance: DataProvenance = DataProvenance.SIMULATED
    advisory_notes: Optional[str] = None

    model_config = ConfigDict(from_attributes=True)


class ProactiveSatelliteAlert(BaseModel):
    """
    Simulated or real alert generated by proactive automated scanning of known vulnerable zones.
    """
    alert_id: str
    region_id: str
    region_name: str
    anomaly_type: str  # e.g., "rapid_slope_displacement", "river_width_expansion", "snow_depletion"
    detected_at: datetime
    lat: float
    lng: float
    estimated_radius_km: float
    severity: str  # "high", "medium", "low"
    description: str
    data_provenance: DataProvenance = DataProvenance.SIMULATED
    correlated_incident_id: Optional[str] = None

    model_config = ConfigDict(from_attributes=True)


class SatelliteCorrelationResult(BaseModel):
    """
    Outcome of evaluating satellite passes against a reported incident.
    """
    status: ObservationStatus
    relevance_score: float = Field(0.0, ge=0.0, le=1.0)
    best_observation: Optional[SatelliteObservation] = None
    evaluated_observations_count: int = 0
    spatial_distance_km: Optional[float] = None
    temporal_delta_hours: Optional[float] = None
    warnings: List[str] = Field(default_factory=list)
    reasons: List[str] = Field(default_factory=list)
    data_provenance: DataProvenance = DataProvenance.SIMULATED
    human_review_required: bool = True

    model_config = ConfigDict(from_attributes=True)
